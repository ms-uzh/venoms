import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { normalizeTermKey } from "./lib/terms.mjs";
import { readFullContentIndex } from "./lib/content.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDir = path.join(root, ".generated");
const seedFile = path.join(outputDir, "search-seed.sql");
const versionFile = path.join(outputDir, "search-version.txt");
const SEARCH_SCHEMA_VERSION = 2;

const { pages } = await readFullContentIndex(root);
const ordered = [...pages].sort((a, b) => a.slug.localeCompare(b.slug));

// Content hash — stable across runs (no timestamps), independent of table names.
// Covers every field that lands in the search tables, so distinct content ⇒ distinct version.
const canonical = JSON.stringify({
  schema: SEARCH_SCHEMA_VERSION,
  pages: ordered.map((page) => [
    page.slug, page.title, page.kind, page.sourcePath, page.description, page.formula,
    page.nominalMass, page.precursor1, page.family, page.species, page.level, page.confidence,
    page.categories, page.tags, page.bodyText,
  ]),
});
const version = createHash("sha256").update(canonical).digest("hex").slice(0, 12);

const P = `pages_${version}`;
const T = `page_terms_${version}`;
const F = `pages_fts_${version}`;

const ddl = [
  `DROP TABLE IF EXISTS ${P};`,
  `DROP TABLE IF EXISTS ${T};`,
  `DROP TABLE IF EXISTS ${F};`,
  `CREATE TABLE ${P} (
    slug TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    kind TEXT NOT NULL,
    source_path TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    formula TEXT NOT NULL DEFAULT '',
    nominal_mass REAL,
    precursor1 REAL,
    family_json TEXT NOT NULL DEFAULT '[]',
    species_json TEXT NOT NULL DEFAULT '[]',
    level TEXT NOT NULL DEFAULT '',
    confidence TEXT NOT NULL DEFAULT '',
    categories_json TEXT NOT NULL DEFAULT '[]',
    tags_json TEXT NOT NULL DEFAULT '[]'
  );`,
  `CREATE TABLE ${T} (
    page_slug TEXT NOT NULL,
    term_type TEXT NOT NULL,
    term_value TEXT NOT NULL,
    term_key TEXT NOT NULL
  );`,
  `CREATE INDEX idx_${T}_type_key ON ${T}(term_type, term_key);`,
  `CREATE INDEX idx_${T}_slug ON ${T}(page_slug);`,
  `CREATE VIRTUAL TABLE ${F} USING fts5(
    slug UNINDEXED, title, body, formula, categories, tags, families, species,
    tokenize = 'porter unicode61'
  );`,
];

const sql = [
  "-- Generated by scripts/build-search-index.mjs. Do not edit by hand.",
  `-- Search version: ${version}`,
  ...ddl,
  ...ordered.flatMap(pageToSql),
  "",
].join("\n");

await mkdir(outputDir, { recursive: true });
await writeFile(seedFile, sql, "utf8");
await writeFile(versionFile, version, "utf8");

console.log(`Generated D1 seed for ${ordered.length} pages (version ${version}) at ${path.relative(root, seedFile)}`);

function pageToSql(page) {
  const rows = [
    `INSERT INTO ${P} (slug, title, kind, source_path, description, formula, nominal_mass, precursor1, family_json, species_json, level, confidence, categories_json, tags_json) VALUES (${sqlString(page.slug)}, ${sqlString(page.title)}, ${sqlString(page.kind)}, ${sqlString(page.sourcePath)}, ${sqlString(page.description)}, ${sqlString(page.formula)}, ${sqlNumber(page.nominalMass)}, ${sqlNumber(page.precursor1)}, ${sqlString(JSON.stringify(page.family))}, ${sqlString(JSON.stringify(page.species))}, ${sqlString(page.level)}, ${sqlString(page.confidence)}, ${sqlString(JSON.stringify(page.categories))}, ${sqlString(JSON.stringify(page.tags))});`,
    `INSERT INTO ${F} (slug, title, body, formula, categories, tags, families, species) VALUES (${sqlString(page.slug)}, ${sqlString(page.title)}, ${sqlString(page.bodyText)}, ${sqlString(page.formula)}, ${sqlString(page.categories.join(" "))}, ${sqlString(page.tags.join(" "))}, ${sqlString(page.family.join(" "))}, ${sqlString(page.species.join(" "))});`,
  ];

  const terms = [
    ...page.categories.map((value) => ["category", value]),
    ...page.tags.map((value) => ["tag", value]),
    ...page.family.map((value) => ["family", value]),
    ...page.species.map((value) => ["species", value]),
    page.formula ? ["formula", page.formula] : null,
    page.level ? ["level", page.level] : null,
    page.confidence ? ["confidence", page.confidence] : null,
  ].filter(Boolean);

  for (const [type, value] of terms) {
    rows.push(`INSERT INTO ${T} (page_slug, term_type, term_value, term_key) VALUES (${sqlString(page.slug)}, ${sqlString(type)}, ${sqlString(value)}, ${sqlString(normalizeTermKey(value))});`);
  }

  return rows;
}

function sqlString(value) {
  return `'${String(value ?? "").replaceAll("'", "''")}'`;
}

function sqlNumber(value) {
  return Number.isFinite(value) ? String(value) : "NULL";
}
